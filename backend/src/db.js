import pg from 'pg'
import bcrypt from 'bcryptjs'
import { AsyncLocalStorage } from 'node:async_hooks'

const { Pool } = pg

// PostgreSQL mengembalikan SUM()/COUNT() (bigint) sebagai string. Aplikasi ini
// memakai rupiah bulat yang jauh di bawah batas aman JavaScript, jadi diubah
// ke Number supaya JSON ke frontend berupa angka (bukan "200000").
pg.types.setTypeParser(20, (v) => Number(v))
// Kolom DATE dikirim apa adanya sebagai 'YYYY-MM-DD' (bukan objek Date yang bergeser mengikuti zona waktu server).
pg.types.setTypeParser(1082, (v) => v)
const DATABASE_URL = process.env.DATABASE_URL
if (!DATABASE_URL) {
  console.warn('DATABASE_URL belum diset. Backend PostgreSQL membutuhkan DATABASE_URL.')
}

const pool = new Pool({
  connectionString: DATABASE_URL,
  max: Number(process.env.DB_POOL_MAX || 10),
  idleTimeoutMillis: Number(process.env.DB_IDLE_TIMEOUT_MS || 30000),
  connectionTimeoutMillis: Number(process.env.DB_CONNECTION_TIMEOUT_MS || 10000),
  ssl: process.env.DB_SSL === 'true' ? { rejectUnauthorized: process.env.DB_SSL_REJECT_UNAUTHORIZED !== 'false' } : undefined
})

// Tanpa listener ini, koneksi idle yang putus (restart database, jaringan) akan
// melempar 'error' tak tertangani dan mematikan seluruh proses. Pool akan
// otomatis membuat koneksi baru pada query berikutnya.
pool.on('error', (err) => { console.error('Koneksi database idle error:', err.message) })

const txStorage = new AsyncLocalStorage()
const IDENTITY_TABLES = new Set(['users', 'ledger', 'audit_log', 'tagihan', 'topup_request', 'produk'])

function pgSql(sql) {
  let out = String(sql)
    .replace(/datetime\('now'\)/gi, 'CURRENT_TIMESTAMP')
    .replace(/date\('now','\+7 hours'\)/gi, "(CURRENT_TIMESTAMP + INTERVAL '7 hours')::date")
    .replace(/strftime\('%Y-%m','now','\+7 hours'\)/gi, "to_char(CURRENT_TIMESTAMP + INTERVAL '7 hours', 'YYYY-MM')")
    .replace(/strftime\('%Y-%m',\s*([a-zA-Z0-9_.]+)\)/gi, "to_char($1::timestamptz, 'YYYY-MM')")
    .replace(/date\(\s*([^,]+?)\s*,\s*'\+7 hours'\s*\)/gi, "(($1::timestamptz + INTERVAL '7 hours')::date)")
    .replace(/date\(\s*\?,\s*'-'\s*\|\|\s*\?\s*\|\|\s*' day'\s*\)/gi, "($1::date - ($2 * INTERVAL '1 day'))::date")

  let index = 0
  out = out.replace(/\?/g, () => `$${++index}`)
  return out
}

function currentExecutor() {
  return txStorage.getStore() || pool
}

class Statement {
  constructor(sql) {
    this.originalSql = sql
    this.sql = pgSql(sql)
  }

  async get(...params) {
    const result = await currentExecutor().query(this.sql, params)
    return result.rows[0]
  }

  async all(...params) {
    const result = await currentExecutor().query(this.sql, params)
    return result.rows
  }

  async run(...params) {
    let sql = this.sql
    const insertMatch = sql.match(/^\s*INSERT\s+INTO\s+([a-zA-Z_][\w]*)/i)
    if (insertMatch && IDENTITY_TABLES.has(insertMatch[1].toLowerCase()) && !/\bRETURNING\b/i.test(sql)) {
      sql += ' RETURNING id'
    }
    const result = await currentExecutor().query(sql, params)
    return {
      changes: result.rowCount,
      lastInsertRowid: result.rows[0]?.id ?? null
    }
  }
}

export const db = {
  prepare(sql) {
    return new Statement(sql)
  },

  transaction(fn) {
    return async (...args) => {
      const client = await pool.connect()
      try {
        await client.query('BEGIN')
        const result = await txStorage.run(client, () => fn(...args))
        await client.query('COMMIT')
        return result
      } catch (error) {
        await client.query('ROLLBACK')
        throw error
      } finally {
        client.release()
      }
    }
  },

  async exec(sql) {
    return currentExecutor().query(sql)
  },

  async close() {
    await pool.end()
  },

  pool
}

export async function initDb() {
  if (!DATABASE_URL) throw new Error('DATABASE_URL wajib diisi untuk PostgreSQL')

  await db.exec(`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      role TEXT NOT NULL CHECK(role IN ('admin','ortu','pic','siswa')),
      nama TEXT NOT NULL,
      username TEXT UNIQUE,
      password_hash TEXT,
      pin_hash TEXT,
      outlet TEXT,
      active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS siswa_profil (
      user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      ortu_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
      kelas TEXT,
      nis TEXT UNIQUE
    );

    CREATE TABLE IF NOT EXISTS ledger (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      siswa_id INTEGER NOT NULL REFERENCES users(id),
      tipe TEXT NOT NULL CHECK(tipe IN ('topup','pembelian','tarik_tunai','bayar_tagihan','penyesuaian')),
      nominal INTEGER NOT NULL,
      keterangan TEXT,
      ref_tabel TEXT,
      ref_id INTEGER,
      dibuat_oleh INTEGER REFERENCES users(id),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_ledger_siswa ON ledger(siswa_id);
    CREATE INDEX IF NOT EXISTS idx_ledger_created ON ledger(created_at DESC);

    CREATE TABLE IF NOT EXISTS audit_log (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      aktor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
      aksi TEXT NOT NULL,
      perubahan TEXT NOT NULL DEFAULT '',
      ip TEXT,
      ref_tabel TEXT,
      ref_id INTEGER,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_log(created_at DESC);
    CREATE INDEX IF NOT EXISTS idx_audit_actor ON audit_log(aktor_id);

    CREATE TABLE IF NOT EXISTS tagihan (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      siswa_id INTEGER NOT NULL REFERENCES users(id),
      nama TEXT NOT NULL,
      nominal INTEGER NOT NULL CHECK(nominal > 0),
      jatuh_tempo DATE,
      status TEXT NOT NULL DEFAULT 'belum_bayar' CHECK(status IN ('belum_bayar','lunas','batal')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_tagihan_siswa ON tagihan(siswa_id);

    CREATE TABLE IF NOT EXISTS topup_request (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      siswa_id INTEGER NOT NULL REFERENCES users(id),
      ortu_id INTEGER NOT NULL REFERENCES users(id),
      nominal INTEGER NOT NULL CHECK(nominal > 0),
      kode_unik INTEGER NOT NULL,
      tagihan_id INTEGER REFERENCES tagihan(id),
      status TEXT NOT NULL DEFAULT 'menunggu' CHECK(status IN ('menunggu','disetujui','ditolak')),
      alasan_tolak TEXT,
      pernah_ditolak INTEGER NOT NULL DEFAULT 0 CHECK(pernah_ditolak IN (0,1)),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      diproses_oleh INTEGER REFERENCES users(id),
      diproses_at TIMESTAMPTZ
    );
    CREATE INDEX IF NOT EXISTS idx_topup_status ON topup_request(status, id DESC);
    CREATE INDEX IF NOT EXISTS idx_topup_siswa ON topup_request(siswa_id);

    CREATE TABLE IF NOT EXISTS produk (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nama TEXT NOT NULL,
      harga INTEGER NOT NULL CHECK(harga > 0),
      outlet TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_produk_outlet ON produk(outlet);

    CREATE TABLE IF NOT EXISTS qr_used (
      token_hash TEXT PRIMARY KEY,
      siswa_id INTEGER NOT NULL REFERENCES users(id),
      used_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_qr_used_time ON qr_used(used_at);
  `)

  // Migrasi ringan untuk database yang sudah terlanjur dibuat sebelum fitur
  // bukti transfer ditambahkan. PostgreSQL aman menjalankan IF NOT EXISTS
  // berulang kali setiap server start.
  await db.exec(`
    CREATE TABLE IF NOT EXISTS kas_outlet (
      outlet TEXT NOT NULL,
      tanggal DATE NOT NULL,
      kas_awal INTEGER NOT NULL CHECK (kas_awal >= 0),
      PRIMARY KEY (outlet, tanggal)
    )
  `)
  await db.exec(`
    CREATE TABLE IF NOT EXISTS pin_percobaan (
      siswa_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      salah INTEGER NOT NULL DEFAULT 0,
      terkunci_sampai TIMESTAMPTZ
    )
  `)
  await db.exec(`ALTER TABLE siswa_profil ADD COLUMN IF NOT EXISTS limit_harian_aktif BOOLEAN NOT NULL DEFAULT FALSE`)
  await db.exec(`ALTER TABLE siswa_profil ADD COLUMN IF NOT EXISTS limit_harian INTEGER NOT NULL DEFAULT 25000`)
  await db.exec(`ALTER TABLE siswa_profil ADD COLUMN IF NOT EXISTS kartu_diblokir BOOLEAN NOT NULL DEFAULT FALSE`)
  await db.exec(`
    CREATE TABLE IF NOT EXISTS pembatalan (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ledger_id INTEGER NOT NULL UNIQUE REFERENCES ledger(id),
      ledger_balik_id INTEGER NOT NULL REFERENCES ledger(id),
      alasan TEXT NOT NULL,
      dibatalkan_oleh INTEGER REFERENCES users(id),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS tutup_kas (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      outlet TEXT NOT NULL,
      tanggal DATE NOT NULL,
      kas_awal INTEGER NOT NULL,
      sudah_ditarik INTEGER NOT NULL,
      diharapkan INTEGER NOT NULL,
      kas_fisik INTEGER NOT NULL,
      selisih INTEGER NOT NULL,
      ditutup_oleh INTEGER REFERENCES users(id),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (outlet, tanggal)
    );
  `)
  await db.exec(`ALTER TABLE users ADD COLUMN IF NOT EXISTS wajib_ganti_password BOOLEAN NOT NULL DEFAULT FALSE`)
  await db.exec(`ALTER TABLE users ADD COLUMN IF NOT EXISTS hubungan TEXT`)
  await db.exec(`ALTER TABLE users ADD COLUMN IF NOT EXISTS no_hp TEXT`)
  await db.exec(`ALTER TABLE users ADD COLUMN IF NOT EXISTS email TEXT`)
  await db.exec(`ALTER TABLE tagihan DROP CONSTRAINT IF EXISTS tagihan_status_check`)
  await db.exec(`ALTER TABLE tagihan ADD CONSTRAINT tagihan_status_check CHECK(status IN ('belum_bayar','lunas','batal'))`)
  await db.exec(`ALTER TABLE tagihan ADD COLUMN IF NOT EXISTS batal_alasan TEXT`)
  await db.exec(`ALTER TABLE tagihan ADD COLUMN IF NOT EXISTS batal_at TIMESTAMPTZ`)
  await db.exec(`ALTER TABLE topup_request ADD COLUMN IF NOT EXISTS bukti_data TEXT`)
  await db.exec(`ALTER TABLE topup_request ADD COLUMN IF NOT EXISTS bukti_mime TEXT`)
  await db.exec(`ALTER TABLE topup_request ADD COLUMN IF NOT EXISTS bukti_nama TEXT`)
  await db.exec(`ALTER TABLE topup_request ADD COLUMN IF NOT EXISTS bukti_ukuran INTEGER`)

  await db.prepare("UPDATE produk SET outlet = 'kantin_utama' WHERE lower(outlet) = 'kantin utama'").run()
  await db.prepare("UPDATE produk SET outlet = 'kantin_b' WHERE lower(outlet) IN ('kantin blok b', 'kantin b')").run()
  await db.prepare("UPDATE produk SET outlet = 'koperasi' WHERE lower(outlet) = 'koperasi sekolah'").run()
}

export const OUTLET = Object.freeze({
  KANTIN_UTAMA: 'kantin_utama',
  KANTIN_B: 'kantin_b',
  KOPERASI: 'koperasi'
})

export function namaOutlet(key) {
  return {
    [OUTLET.KANTIN_UTAMA]: 'Kantin Utama',
    [OUTLET.KANTIN_B]: 'Kantin Blok B',
    [OUTLET.KOPERASI]: 'Koperasi Sekolah'
  }[key] || key || ''
}

export async function saldoSiswa(siswaId) {
  const row = await db.prepare('SELECT COALESCE(SUM(nominal), 0) AS saldo FROM ledger WHERE siswa_id = ?').get(siswaId)
  return Number(row?.saldo || 0)
}

// Akun pertama untuk produksi. Dibuat HANYA bila tabel users kosong dan
// ADMIN_USERNAME + ADMIN_PASSWORD (min. 12 karakter) diisi di environment.
// Setelah login pertama, segera ganti password dari menu Admin lalu hapus
// ADMIN_PASSWORD dari environment hosting.
export async function ensureInitialAdmin() {
  const totalUsers = (await db.prepare('SELECT COUNT(*) AS n FROM users').get()).n
  if (Number(totalUsers) > 0) return false
  const username = (process.env.ADMIN_USERNAME || '').trim()
  const password = process.env.ADMIN_PASSWORD || ''
  if (!username || password.length < 12) {
    console.warn('Database belum punya pengguna. Isi ADMIN_USERNAME dan ADMIN_PASSWORD (min. 12 karakter) lalu start ulang untuk membuat admin pertama.')
    return false
  }
  await db.prepare('INSERT INTO users (role, nama, username, password_hash, pin_hash, wajib_ganti_password) VALUES (?, ?, ?, ?, ?, TRUE)')
    .run('admin', process.env.ADMIN_NAMA || 'Admin Yayasan', username, bcrypt.hashSync(password, 12), null)
  console.log(`Admin pertama "${username}" dibuat.`)
  return true
}

// Data demo (password lemah!) hanya untuk development. Di produksi hanya jalan
// kalau SEED_DEMO=true dipasang dengan sengaja.
export async function ensureDemoData() {
  if (process.env.NODE_ENV === 'production' && process.env.SEED_DEMO !== 'true') {
    return ensureInitialAdmin()
  }
  const totalUsers = (await db.prepare('SELECT COUNT(*) AS n FROM users').get()).n
  if (Number(totalUsers) > 0) return false

  const hash = (s) => bcrypt.hashSync(s, 10)
  const tx = await db.transaction(async () => {
    const insertUser = db.prepare(`INSERT INTO users (role, nama, username, password_hash, pin_hash) VALUES (?, ?, ?, ?, ?)`)
    const insertPic = db.prepare(`INSERT INTO users (role, nama, username, password_hash, pin_hash, outlet) VALUES (?, ?, ?, ?, ?, ?)`)
    const admin = await insertUser.run('admin', 'Admin Yayasan', 'admin', hash('admin123'), null)
    const ortu = await insertUser.run('ortu', 'Ibu Sari', 'ortu.sari', hash('123456'), null)
    await insertPic.run('pic', 'PIC Kantin Utama', 'pic.kantin.utama', hash('123456'), null, OUTLET.KANTIN_UTAMA)
    await insertPic.run('pic', 'PIC Kantin Blok B', 'pic.kantin.b', hash('123456'), null, OUTLET.KANTIN_B)
    await insertPic.run('pic', 'PIC Koperasi Sekolah', 'pic.koperasi', hash('123456'), null, OUTLET.KOPERASI)
    const aditya = await insertUser.run('siswa', 'Aditya Pratama', 'aditya.p', hash('123456'), hash('135790'))
    const kayla = await insertUser.run('siswa', 'Kayla Pratama', 'kayla.p', hash('123456'), hash('135790'))

    const insertProfil = db.prepare('INSERT INTO siswa_profil (user_id, ortu_id, kelas, nis) VALUES (?, ?, ?, ?)')
    await insertProfil.run(aditya.lastInsertRowid, ortu.lastInsertRowid, '7B', '24071023')
    await insertProfil.run(kayla.lastInsertRowid, ortu.lastInsertRowid, '4A', '24040518')

    const insertTagihan = db.prepare(`INSERT INTO tagihan (siswa_id, nama, nominal, jatuh_tempo) VALUES (?, ?, ?, ?)`)
    await insertTagihan.run(aditya.lastInsertRowid, 'SPP September 2026', 450000, '2026-09-10')
    await insertTagihan.run(kayla.lastInsertRowid, 'SPP September 2026', 400000, '2026-09-10')

    const insertProduk = db.prepare('INSERT INTO produk (nama, harga, outlet) VALUES (?, ?, ?)')
    for (const product of [
      ['Paket A — nasi + ayam + teh', 15000, OUTLET.KANTIN_UTAMA],
      ['Paket B — nasi + telur + teh', 12000, OUTLET.KANTIN_UTAMA],
      ['Mie ayam', 13000, OUTLET.KANTIN_UTAMA],
      ['Air mineral 600 ml', 4000, OUTLET.KANTIN_UTAMA],
      ['Buku tulis 38 lbr', 5000, OUTLET.KOPERASI]
    ]) await insertProduk.run(...product)

    return { adminId: admin.lastInsertRowid }
  })

  await tx()
  console.log('PostgreSQL kosong → akun demo dibuat otomatis.')
  return true
}
